/** The catalog: each built-in indicator's id, name, inputs, lines and levels. */
const catalog = descriptors.map((d) => ({
  id: d.id,
  name: d.name,
  shortName: d.shortName ?? d.id.toUpperCase(),
  placement: d.placement,
  params: d.defaultConfig,
  ...(d.inputs ? { inputs: d.inputs } : {}),
  plots: (d.plots ?? []).map((p) => ({ key: p.key, title: p.title, kind: p.kind ?? 'line' })),
  ...(d.levels?.length ? { levels: d.levels } : {}),
  ...(d.scale ? { scale: d.scale } : {}),
}));

/**
 * A built-in input's type: one of its kinds (offered as you type, any text
 * still taken, as it was), a price or a line, a number, or text.
 */
function inputType(value, input = {}) {
  if (input.options) return `${input.options.map((o) => `'${o}'`).join(' | ')} | (string & {})`;
  if (input.source || typeof value !== 'number') return typeof value === 'boolean' ? 'boolean' : 'string';
  return 'NumberParam';
}

/** What an input's note says: its label, its range, where a source may come from, and its default. */
function inputNote(value, input = {}) {
  const parts = [];
  if (input.label) parts.push(`${input.label}.`);
  if (input.source) parts.push("A price (`'close'`, `'hl2'` …) or another indicator's line (`indicatorSource(instanceId, key)`).");
  const range = [input.min != null && `at least ${input.min}`, input.max != null && `at most ${input.max}`, input.step != null && `in steps of ${input.step}`]
    .filter(Boolean).join(', ');
  if (range) parts.push(`${range[0].toUpperCase()}${range.slice(1)}.`);
  parts.push(`Default ${typeof value === 'string' ? `\`'${value}'\`` : value}.`);
  return parts.join(' ');
}

/** `BuiltInIndicators`: each built-in's inputs and lines as types, for `addIndicator` and an editor's hints. */
function indicatorTypes() {
  const out = [
    '// Generated by scripts/gen-ai-docs.mjs from the indicator registry. Do not edit by hand.',
    "import type { NumberParam } from './indicator.js';",
    '',
    '/**',
    ` * The ${catalog.length} built-in indicators, by id: the inputs`,
    ' * `chart.addIndicator(id, params)` takes, each optional (its default in its',
    ' * note), and the keys of the lines it draws, as',
    ' * `chart.getIndicatorOutput(instanceId)` and `indicatorSource(instanceId, key)`',
    " * name them (an output may hold a few more, such as Supertrend's `trend`).",
    ' * The chart adds five that read other symbols, `compareSymbol` (on the',
    ' * price pane), `compareSymbolPane` (in a pane of its own), `spread`,',
    ' * `correlation` and `correlationlog`; they take any inputs.',
    ' */',
    'export interface BuiltInIndicators {',
  ];
  for (const ind of catalog) {
    const where = ind.placement === 'overlay' ? 'on the price pane' : 'in a pane of its own';
    const lines = ind.plots.map((p) => `\`${p.key}\` (${p.title})`).join(', ');
    const levels = ind.levels?.length ? ` Levels at ${ind.levels.join(', ')}.` : '';
    out.push(`  /** ${ind.name}, ${where}. ${lines ? `Lines: ${lines}.` : 'No lines.'}${levels} */`);
    out.push(`  ${ind.id}: {`);
    const params = Object.entries(ind.params);
    out.push(params.length ? '    params: {' : '    params: {};');
    for (const [key, value] of params) {
      const input = ind.inputs?.[key];
      out.push(`      /** ${inputNote(value, input)} */`);
      out.push(`      ${key}?: ${inputType(value, input)};`);
    }
    if (params.length) out.push('    };');
    out.push(`    lines: ${ind.plots.length ? ind.plots.map((p) => `'${p.key}'`).join(' | ') : 'never'};`);
    out.push('  };');
  }
  out.push('}', '');
  return out.join('\n');
}

/** What a style key's kind takes, as the reference says it. */
const STYLE_VALUES = {
  color: 'a CSS colour',
  lineStyle: "`'solid'`, `'dashed'` or `'dotted'`",
  width: 'a width, px',
  boolean: '`true` or `false`',
};

/** The skill's list of every style key, grouped by the part of the chart it styles. */
function styleKeysMarkdown() {
  const groups = new Map();
  for (const [key, kind] of Object.entries(commons.CHART_STYLE_KEYS)) {
    const [head, second] = key.split('.');
    const group = head === 'series' ? `series.${second}` : head;
    groups.set(group, [...(groups.get(group) ?? []), [key, kind]]);
  }
  return [
    '<!-- Generated by scripts/gen-ai-docs.mjs from CHART_STYLE_KEYS. Do not edit by hand. -->',
    '',
    '# Style keys',
    '',
    `${Object.keys(commons.CHART_STYLE_KEYS).length} keys, each one part of the chart's look apart from its theme:`,
    "`chart.applyOverrides({ 'grid.vertical.visible': false })`, `overrides` in the chart's options, or the",
    "React/Vue/Svelte `overrides` prop. A value sets a key and `null` takes it away. `CHART_STYLE_KEYS`, exported",
    'from `@tradecanvas/chart`, holds them with their kinds; `chart.getStyleValue(key)` is what one resolves to now.',
    '',
    '- **Candles**: `series.candlestick.upColor` and `downColor` colour the bodies, and the wicks with them;',
    '  `wickUpColor` and `wickDownColor` give the wicks colours of their own.',
    '- **Other chart types** (`series.<type>.*`) take their up and down colours from `series.candlestick.*`',
    "  when they have none, line colours and widths from `series.line.*`, area fills from `series.area.*`,",
    "  then from the theme.",
    '- Values: ' + Object.entries(STYLE_VALUES).map(([kind, text]) => `${kind} is ${text}`).join('; ') + '.',
    '',
    ...[...groups].flatMap(([group, keys]) => [
      `## ${group}`,
      '',
      '| Key | Kind |',
      '|---|---|',
      ...keys.map(([key, kind]) => `| \`${key}\` | ${kind} |`),
      '',
    ]),
  ].join('\n');
}

const cell = (s) => String(s).replace(/\|/g, '\\|');
const paramsText = (params) => Object.entries(params).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(', ') || '—';
const sourceNote = (ind) => (ind.inputs && Object.values(ind.inputs).some((i) => i.source) ? ' ✓' : '');

function indicatorsMarkdown() {
  const section = (placement, title, blurb) => {
    const rows = catalog.filter((i) => i.placement === placement);
    return [
      `## ${title} (${rows.length})`,
      '',
      blurb,
      '',
      '| id | Name | Default params | Lines (key: title) | Levels | Source |',
      '|---|---|---|---|---|---|',
      ...rows.map((i) => `| \`${i.id}\` | ${cell(i.name)} | ${cell(paramsText(i.params))} | ${cell(i.plots.map((p) => `${p.key}: ${p.title}`).join(', ') || '—')} | ${i.levels?.join(', ') ?? '—'} |${sourceNote(i)} |`),
      '',
    ].join('\n');
  };
  return [
    '<!-- Generated by scripts/gen-ai-docs.mjs from the indicator registry. Do not edit by hand. -->',
    '',
    '# Built-in indicators',
    '',
    `${catalog.length} indicators. Add one with \`chart.addIndicator(id, params)\`; params you leave out take the defaults below.`,
    'An indicator\'s values at bar `i` are `chart.getIndicatorOutput(instanceId).series[i]`, an object keyed by the line keys listed here.',
    '"Source ✓" means it has a `source` input: a price (`close`, `open`, `high`, `low`, `hl2`, `hlc3`, `ohlc4`, `hlcc4`) or another indicator\'s line (`indicatorSource(instanceId, key)`).',
    '',
    section('overlay', 'On the price pane', 'Drawn over the candles, on the price scale.'),
    section('panel', 'In a pane of their own', 'Drawn in a pane under the chart (`addIndicator(id, params, \'bottom\' | \'top\')`), with their own scale and levels.'),
  ].join('\n');
}

